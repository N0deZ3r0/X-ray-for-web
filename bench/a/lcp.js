// Лаборатория LCP.
//
// Критерий Э1 требует, чтобы прибор не ухудшал LCP больше чем на 5%. Закрыть
// его автоматизацией не вышло по двум причинам, обе записаны в
// bench/perf/README.md: вкладку под управлением Chrome считает скрытой и не
// отрисовывает (LCP просто не существует), а разброс load на живых сайтах
// достигал восьмикратного — на таком шуме 5% неразличимы.
//
// Здесь снято и то и другое. Окно настоящее и видимое, значит LCP есть.
// Страница локальная, значит сеть не шумит. Замеров много, и сравниваются не
// средние, а распределения: если серии перекрываются, лаборатория говорит
// «различить нельзя» — и это честный ответ, а не отсутствие ответа.

(() => {
  'use strict';

  const КЛЮЧ = 'xray-lcp-v1';
  const ЦЕЛЬ = 20; // сколько замеров набирает одна серия за нажатие

  const $ = (id) => document.getElementById(id);

  // ── Есть ли прибор ────────────────────────────────────────────────────────
  //
  // Определяется ровно тем приёмом, который прибор сам называет своим пределом
  // (предел 1 в 06-limits.md): обёрнутая функция не выглядит нативной. Здесь
  // это не обход, а необходимость — лаборатория обязана знать, какую серию
  // ведёт, и спрашивать об этом человека значило бы получить ошибки разметки.
  function приборЕсть() {
    try {
      const s = Function.prototype.toString.call(HTMLCanvasElement.prototype.toDataURL);
      return !/\[native code\]/.test(s);
    } catch (e) {
      return false;
    }
  }

  const серия = приборЕсть() ? 'сПрибором' : 'безПрибора';

  // ── Хранилище ─────────────────────────────────────────────────────────────

  function прочитать() {
    try {
      const s = JSON.parse(localStorage.getItem(КЛЮЧ) || '{}');
      return { сПрибором: s.сПрибором || [], безПрибора: s.безПрибора || [], осталось: s.осталось || 0 };
    } catch (e) {
      return { сПрибором: [], безПрибора: [], осталось: 0 };
    }
  }

  function записать(s) {
    try {
      localStorage.setItem(КЛЮЧ, JSON.stringify(s));
    } catch (e) {}
  }

  // ── Снятие замера ─────────────────────────────────────────────────────────
  //
  // LCP объявляется окончательным только когда страница уходит из видимости
  // или пользователь взаимодействует. Мы перезагружаем сами, поэтому берём
  // последнюю запись на момент, когда всё загрузилось и очередь опустела.

  let последнийLCP = 0;
  try {
    new PerformanceObserver((список) => {
      for (const e of список.getEntries()) последнийLCP = e.startTime;
    }).observe({ type: 'largest-contentful-paint', buffered: true });
  } catch (e) {}

  function fcp() {
    const e = performance.getEntriesByName('first-contentful-paint')[0];
    return e ? e.startTime : 0;
  }

  // Загрузка, начавшаяся в скрытой вкладке, НАВСЕГДА лишается LCP: Chrome не
  // отрисовывает фоновую вкладку и отказывается называть отрисовку крупнейшего
  // элемента. Именно на это налетел автоматизированный замер (bench/perf), и на
  // это же налетит любой, кто откроет страницу вторым щелчком мыши в фоне.
  // Такой замер надо не тихо потерять, а назвать негодным вслух.
  function началасьСкрытой() {
    try {
      const записи = performance.getEntriesByType('visibility-state');
      const первыйПоказ = записи.find((e) => e.name === 'visible');
      const скрытаВНачале = записи.some((e) => e.name === 'hidden' && e.startTime === 0);
      // Скрыта на нуле и показана позже — значит загрузка шла в фоне.
      return скрытаВНачале && (!первыйПоказ || первыйПоказ.startTime > 0);
    } catch (e) {
      return false;
    }
  }

  function навигация() {
    const n = performance.getEntriesByType('navigation')[0];
    return n || null;
  }

  function снять() {
    const n = навигация();
    return {
      lcp: Math.round(последнийLCP),
      fcp: Math.round(fcp()),
      dcl: n ? Math.round(n.domContentLoadedEventEnd) : 0,
      load: n ? Math.round(n.loadEventEnd) : 0,
      фон: началасьСкрытой(),
    };
  }

  // ── Статистика ────────────────────────────────────────────────────────────
  //
  // Медиана и квартили, а не среднее: одно подвисание сборщика мусора уводит
  // среднее туда, где ни один замер не был.

  const квантиль = (масс, q) => {
    if (!масс.length) return 0;
    const s = [...масс].sort((a, b) => a - b);
    const i = (s.length - 1) * q;
    const низ = Math.floor(i);
    const верх = Math.ceil(i);
    return низ === верх ? s[низ] : s[низ] + (s[верх] - s[низ]) * (i - низ);
  };

  const сводка = (замеры, поле) => {
    const v = замеры.map((x) => x[поле]).filter((x) => x > 0);
    return {
      n: v.length,
      p25: Math.round(квантиль(v, 0.25)),
      med: Math.round(квантиль(v, 0.5)),
      p75: Math.round(квантиль(v, 0.75)),
    };
  };

  // ── Отрисовка ─────────────────────────────────────────────────────────────

  function строкаТаблицы(имя, a, b) {
    const проц =
      a.med > 0 && b.med > 0 ? (((b.med - a.med) / a.med) * 100).toFixed(1) + '%' : '—';
    return (
      '<tr><td>' + имя + '</td>' +
      '<td>' + (a.n ? a.med : '—') + '</td>' +
      '<td>' + (a.n ? a.p25 + '–' + a.p75 : '—') + '</td>' +
      '<td>' + (b.n ? b.med : '—') + '</td>' +
      '<td>' + (b.n ? b.p25 + '–' + b.p75 : '—') + '</td>' +
      '<td>' + проц + '</td></tr>'
    );
  }

  function нарисовать() {
    const s = прочитать();
    const без = s.безПрибора;
    const с = s.сПрибором;

    $('state').textContent =
      'Эта загрузка: ' + (серия === 'сПрибором' ? 'ПРИБОР ЕСТЬ' : 'прибора нет') +
      '.  Набрано: без прибора ' + без.length + ', с прибором ' + с.length +
      (s.осталось ? '.  Осталось в серии: ' + s.осталось : '.');

    const поля = [
      ['LCP', 'lcp'],
      ['FCP', 'fcp'],
      ['DCL', 'dcl'],
      ['load', 'load'],
    ];

    let html =
      '<table><tr><th>метрика, мс</th>' +
      '<th>без: медиана</th><th>без: 25–75%</th>' +
      '<th>с: медиана</th><th>с: 25–75%</th><th>разница</th></tr>';
    for (const [имя, поле] of поля) {
      html += строкаТаблицы(имя, сводка(без, поле), сводка(с, поле));
    }
    html += '</table>';
    $('table').innerHTML = html;

    $('verdict').className = 'verdict';
    $('verdict').textContent = вердикт(без, с);
  }

  // ── Вердикт ───────────────────────────────────────────────────────────────
  //
  // Главное правило проекта действует и здесь: сказать «не знаю» можно, сказать
  // больше измеренного — нельзя. Поэтому вердикт бывает трёх видов, и «нельзя
  // различить» — полноценный из них, а не отговорка.

  function вердикт(без, с) {
    const МИНИМУМ = 10;
    if (без.length < МИНИМУМ || с.length < МИНИМУМ) {
      return (
        'Нужно хотя бы по ' + МИНИМУМ + ' замеров в каждой серии. Сейчас: без прибора ' +
        без.length + ', с прибором ' + с.length + '. ' +
        (без.length < МИНИМУМ
          ? 'Выключите запись и наберите серию без прибора.'
          : 'Включите запись на localhost:8080 и наберите серию с прибором.')
      );
    }

    const вФоне = [...без, ...с].filter((x) => x.фон).length;
    const a = сводка(без, 'lcp');
    const b = сводка(с, 'lcp');

    if (!a.n || !b.n) {
      if (вФоне) {
        return (
          'LCP не зарегистрирован: ' + вФоне + ' из ' + (без.length + с.length) +
          ' загрузок начались в СКРЫТОЙ вкладке. Chrome не отрисовывает фоновую ' +
          'вкладку и навсегда лишает такую загрузку LCP — не задерживает, а именно ' +
          'не создаёт. Стереть замеры, открыть эту страницу в активной вкладке и ' +
          'не переключаться, пока идёт серия. DCL и load в таблице при этом верны: ' +
          'они от отрисовки не зависят.'
        );
      }
      return (
        'LCP не зарегистрирован ни разу, хотя вкладка была видима. Такое бывает, ' +
        'если крупнейший элемент не попал в окно: прокрутите страницу так, чтобы ' +
        'тёмный блок был виден при загрузке, и наберите серию заново.'
      );
    }

    // Замеры из фона портят обе серии молча: LCP там нет, а DCL с load сняты в
    // других условиях. Считать их вместе с честными нельзя.
    if (вФоне) {
      return (
        'В замерах есть ' + вФоне + ' загрузок из скрытой вкладки — их условия ' +
        'другие, и мешать их с остальными нельзя. Сотрите замеры и наберите серии ' +
        'заново, не уводя вкладку на задний план.'
      );
    }

    const разница = ((b.med - a.med) / a.med) * 100;

    // Перекрытие межквартильных размахов означает, что разница тонет в
    // собственном разбросе замеров. Объявлять по ней вердикт — то же самое
    // враньё, что «47 заблокированных трекеров».
    const перекрываются = a.p25 <= b.p75 && b.p25 <= a.p75;
    if (перекрываются) {
      return (
        'Различить нельзя. Медианы LCP: ' + a.med + ' мс без прибора и ' + b.med +
        ' мс с прибором (' + разница.toFixed(1) + '%), но межквартильные размахи ' +
        'перекрываются: ' + a.p25 + '–' + a.p75 + ' и ' + b.p25 + '–' + b.p75 + '. ' +
        'Это означает, что разница меньше собственного разброса замеров — то есть ' +
        'на этой машине эффект прибора на LCP не измерим. Больше замеров сузит ' +
        'размахи; вердикт «просадки нет» отсюда не следует.'
      );
    }

    const ок = разница <= 5;
    const итог =
      'LCP: ' + a.med + ' мс без прибора, ' + b.med + ' мс с прибором — ' +
      (разница >= 0 ? '+' : '') + разница.toFixed(1) + '%. Размахи не перекрываются, ' +
      'значит разница реальна. Порог Э1 — 5%: ' + (ок ? 'уложились.' : 'ПРЕВЫШЕН.');
    if (!ок) $('verdict').className = 'verdict bad';
    return итог;
  }

  // ── Серия ─────────────────────────────────────────────────────────────────

  function продолжитьСерию() {
    const s = прочитать();
    if (!s.осталось) return;

    const замер = снять();
    s[серия].push(замер);
    s.осталось--;
    записать(s);

    if (s.осталось > 0) {
      // Небольшая пауза: подряд идущие перезагрузки Chrome обслуживает из
      // разогретого состояния, и замер получился бы не про загрузку страницы.
      setTimeout(() => location.reload(), 600);
    } else {
      нарисовать();
    }
  }

  $('run').addEventListener('click', () => {
    const s = прочитать();
    s.осталось = ЦЕЛЬ;
    записать(s);
    нарисовать();
    setTimeout(() => location.reload(), 200);
  });

  $('stop').addEventListener('click', () => {
    const s = прочитать();
    s.осталось = 0;
    записать(s);
    нарисовать();
  });

  $('clear').addEventListener('click', () => {
    записать({ сПрибором: [], безПрибора: [], осталось: 0 });
    нарисовать();
  });

  // Замер снимается после того, как всё загрузилось и метрики устоялись.
  addEventListener('load', () => {
    setTimeout(() => {
      нарисовать();
      const s = прочитать();
      $('stop').hidden = !s.осталось;
      $('run').hidden = Boolean(s.осталось);
      продолжитьСерию();
    }, 400);
  });
})();
