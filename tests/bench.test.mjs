// Тест стенда.
//
// Стенд — то место, куда README посылает человека проверять утверждения прибора
// своими руками. README английский; непереведённая строка на этой странице
// превращает проверяемость в декларацию, и увидит это только тот, у кого
// браузер не на русском, то есть не автор.
//
// Поэтому здесь проверяется полнота перевода стенда на всех строках, которые
// он реально показывает: названия сценариев, примечания, ожидания и надписи
// разметки. И отдельно — что реестр сценариев остался цельным: он тестовый
// оракул, и дыра в нём означает проверку, которая молча перестала выполняться.
//
// Запуск: node tests/bench.test.mjs

import { readFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const стенд = join(dirname(fileURLToPath(import.meta.url)), '..', 'bench', 'a');
const читать = (имя) => readFileSync(join(стенд, имя), 'utf8');

let провал = 0;
function проверка(имя, ок, факт) {
  console.log((ок ? '  ok      ' : '  ПРОВАЛ  ') + имя + (ок ? '' : '  → ' + JSON.stringify(факт)));
  if (!ок) провал++;
}

// ── Реестр сценариев ────────────────────────────────────────────────────────

const песочницаСценариев = { console };
песочницаСценариев.window = песочницаСценариев;
песочницаСценариев.globalThis = песочницаСценариев;
runInNewContext(читать('scenarios.js'), песочницаСценариев, { filename: 'scenarios.js' });

const сценарии = песочницаСценариев.__scenarios || [];

console.log('реестр сценариев');
проверка('реестр загружается и не пуст', сценарии.length > 0, сценарии.length);
проверка(
  'у каждого сценария есть id, этап, название и запуск',
  сценарии.every((s) => s.id && s.этап && s.title && typeof s.run === 'function'),
  сценарии.filter((s) => !(s.id && s.этап && s.title && typeof s.run === 'function')).map((s) => s.id)
);
проверка(
  'идентификаторы не повторяются',
  new Set(сценарии.map((s) => s.id)).size === сценарии.length,
  сценарии.length - new Set(сценарии.map((s) => s.id)).size
);
// Сценарий без ожидания — не оракул, а просто кнопка: сверять с журналом
// прибора будет нечего.
проверка(
  'у каждого сценария сказано, что прибор обязан показать',
  сценарии.every((s) => Array.isArray(s.expect) && s.expect.length > 0),
  сценарии.filter((s) => !(s.expect || []).length).map((s) => s.id)
);
console.log('');

// ── Перевод ─────────────────────────────────────────────────────────────────

// Поднимаем словарь дважды: как его увидит русский браузер и как английский.
function поднять(язык) {
  const п = { console: { warn() {}, log() {} }, navigator: { language: язык }, document: null };
  п.window = п;
  п.globalThis = п;
  // Словарь трогает document только в __trПрименить, который мы не зовём.
  runInNewContext(читать('i18n.js'), п, { filename: 'i18n.js' });
  return п;
}

const английский = поднять('en-US');
const русский = поднять('ru-RU');

const строкиСценариев = [];
for (const s of сценарии) {
  if (s.title) строкиСценариев.push(s.title);
  if (s.note) строкиСценариев.push(s.note);
  for (const e of s.expect || []) строкиСценариев.push(e);
}
const уникальные = [...new Set(строкиСценариев)];

console.log('перевод');
проверка('строк для показа набралось', уникальные.length > 100, уникальные.length);

const кириллица = /[А-Яа-яЁё]/;
const непереведённые = уникальные.filter(
  (s) => кириллица.test(s) && английский.__tr(s) === s
);
проверка(
  'каждая строка сценариев переведена',
  непереведённые.length === 0,
  непереведённые.slice(0, 6)
);

// Названия этапов — Э0…Э6 — это собственные обозначения проекта, такие же как
// S22 у сценария. Они одинаковы в документах, в кнопках фильтра и в тексте, и
// переводить их значило бы завести второе имя одному и тому же этапу.
const безОбозначений = (s) => String(s).replace(/Э\d/g, '');
const осталосьРусским = уникальные.filter((s) => кириллица.test(безОбозначений(английский.__tr(s))));
проверка(
  'в английском выводе не осталось кириллицы',
  осталосьРусским.length === 0,
  осталосьРусским.slice(0, 6)
);

проверка(
  'русскому браузеру ничего не подменяется',
  уникальные.every((s) => русский.__tr(s) === s),
  уникальные.filter((s) => русский.__tr(s) !== s).slice(0, 3)
);
console.log('');

// ── Разметка ────────────────────────────────────────────────────────────────

console.log('разметка');
{
  const html = читать('index.html');
  const ключи = [...html.matchAll(/data-tr="([^"]+)"/g)].map((m) => m[1]);
  проверка('надписи разметки вынесены в data-tr', ключи.length > 0, ключи.length);

  const без = ключи.filter((k) => кириллица.test(k) && английский.__tr(k) === k);
  проверка('каждая надпись разметки переведена', без.length === 0, без);

  // Строка, которую забыли обернуть в __tr, узнаётся по кириллице в коде
  // отрисовки. Реестр сценариев исключён: его строки проходят через __tr.
  const скрипт = html.slice(html.lastIndexOf('<script>'));
  const подозрительные = [...скрипт.matchAll(/(?:textContent|innerHTML)\s*=\s*'([^']*[А-Яа-яЁё][^']*)'/g)]
    .map((m) => m[1])
    .filter((s) => !s.includes('__tr'));
  проверка(
    'в отрисовке не осталось строк мимо словаря',
    подозрительные.length === 0,
    подозрительные
  );
}
console.log('');

// ── Лаборатория LCP ─────────────────────────────────────────────────────────
//
// Статистика — единственное место лаборатории, где ошибка не видна глазом.
// Таблица с числами выглядит убедительно при любом вердикте, а вывод «порог
// соблюдён» из неразличимой разницы — то же самое враньё, что «47
// заблокированных трекеров», только с доверительным интервалом.
//
// Первая редакция сравнивала межквартильные размахи и советовала «набрать
// больше замеров, чтобы они сузились». Размах — свойство распределения, а не
// выборки: он не сужается никогда. Совет был ложным, и поймать это могла только
// проверка вроде этой.

console.log('лаборатория LCP');
{
  const п = {
    console: { warn() {}, log() {} },
    localStorage: { getItem: () => null, setItem() {}, removeItem() {} },
    performance: { getEntriesByType: () => [], getEntriesByName: () => [] },
    PerformanceObserver: class {
      observe() {}
    },
    setTimeout,
    location: { reload() {} },
    document: {
      visibilityState: 'visible',
      getElementById: () => ({
        textContent: '',
        className: '',
        innerHTML: '',
        hidden: false,
        addEventListener() {},
      }),
    },
    addEventListener() {},
  };
  п.window = п;
  п.globalThis = п;
  runInNewContext(readFileSync(join(стенд, 'lcp.js'), 'utf8'), п, { filename: 'lcp.js' });

  const вердикт = п.__lcpВердикт;
  проверка('вердикт доступен для проверки', typeof вердикт === 'function', typeof вердикт);

  const обр = (lcp) => ({ lcp, fcp: lcp - 2, dcl: lcp - 10, load: lcp + 2, фон: false });
  const ряд = (база, n, разброс) =>
    Array.from({ length: n }, (_, i) => обр(база + (i % (2 * разброс + 1)) - разброс));

  if (typeof вердикт === 'function') {
    проверка(
      'мало замеров — вердикта нет, есть указание что делать',
      /Нужно хотя бы по 10/.test(вердикт(ряд(64, 3, 3), [])),
      вердикт(ряд(64, 3, 3), []).slice(0, 40)
    );

    проверка(
      'загрузка из фона названа негодной, а не молча потеряна',
      /СКРЫТОЙ вкладке/.test(
        вердикт(
          ряд(64, 12, 3).map((x) => ({ ...x, lcp: 0, фон: true })),
          ряд(64, 12, 3).map((x) => ({ ...x, lcp: 0, фон: true }))
        )
      ),
      'фон не распознан'
    );

    // Одинаковые серии: разницы нет и порог соблюдён.
    const одинаковые = вердикт(ряд(64, 20, 3), ряд(64, 20, 3));
    проверка(
      'на одинаковых сериях сказано, что разницы не видно',
      /разницы вообще не видно/.test(одинаковые) && /Порог Э1 соблюдён/.test(одинаковые),
      одинаковые.slice(0, 70)
    );

    // Маленькая, но уверенная разница на узком разбросе: порог соблюдён.
    const малая = вердикт(ряд(200, 30, 2), ряд(203, 30, 2));
    проверка(
      'малая уверенная разница признана и порог соблюдён',
      /Порог Э1 соблюдён/.test(малая) && /отличима от нуля/.test(малая),
      малая.slice(0, 70)
    );

    // Явное превышение.
    const много = вердикт(ряд(64, 20, 3), ряд(80, 20, 3));
    проверка('явное превышение названо превышением', /ПРЕВЫШЕН/.test(много), много.slice(0, 60));

    // Широкий разброс: порог не разрешён — и это полноценный ответ.
    const мутно = вердикт(ряд(64, 12, 10), ряд(67, 12, 10));
    проверка(
      'на широком разбросе порог честно объявлен неразрешённым',
      /не разрешён этой выборкой/.test(мутно),
      мутно.slice(0, 60)
    );
    проверка(
      'при этом НЕ сказано «уложились»',
      !/соблюдён/.test(мутно),
      мутно.slice(0, 80)
    );

    // Вердикт обязан быть одинаковым на одних и тех же данных: прибор, дающий
    // разные ответы на одном входе, — не прибор.
    const a = вердикт(ряд(64, 20, 3), ряд(66, 20, 3));
    const b = вердикт(ряд(64, 20, 3), ряд(66, 20, 3));
    проверка('вердикт воспроизводим', a === b, 'два вызова дали разное');
  }
}
console.log('');

console.log(провал ? провал + ' проверок провалено' : 'все проверки стенда пройдены');
process.exit(провал ? 1 : 0);
