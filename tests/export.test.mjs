const проверки = [];
const проверить = (имя, ок, факт) => проверки.push([имя, ок, факт]);

// ── С редакцией: ни одного секрета наружу ───────────────────────────────────
const сРедакцией = E.собратьЭкспорт(session, свод, { редакция: true });
const jsonТекст = JSON.stringify(сРедакцией.данные);
const отчёт = E.собратьОтчёт(session, свод, { редакция: true });

for (const [имя, значение] of Object.entries(СЕКРЕТЫ)) {
  проверить(
    'в JSON нет секрета: ' + имя,
    !jsonТекст.includes(значение),
    'найдено в экспорте'
  );
  проверить(
    'в отчёте нет секрета: ' + имя,
    !отчёт.includes(значение),
    'найдено в отчёте'
  );
}

// ── Но факт наличия поля виден ──────────────────────────────────────────────
