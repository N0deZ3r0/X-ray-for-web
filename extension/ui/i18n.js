// Перевод для панели.
//
// Классический скрипт, а не модуль: панель грузится обычным <script>, и тест
// панели поднимает её через node:vm как обычный скрипт. Ради одного import
// ломать проверяемость не стоит.
//
// Двойник для service worker лежит в background/i18n.js. Дублируется тут
// ровно логика выбора формы — десяток строк. Сами строки не дублируются
// нигде: они лежат в _locales и генерируются из tools/messages.mjs.

(() => {
  'use strict';

  const ЯЗЫК = (chrome.i18n && chrome.i18n.getUILanguage
    ? chrome.i18n.getUILanguage()
    : 'en'
  ).toLowerCase();

  // Формы множественного числа зависят от языка, а не от строки. Русский
  // различает 1 / 2-4 / 5-0, английский — 1 / прочее. Список закрыт намеренно:
  // добавить язык — значит осознанно добавить сюда его правило, а не
  // понадеяться, что подойдёт чужое.
  const РУССКИЙ = ЯЗЫК.startsWith('ru') || ЯЗЫК.startsWith('uk') || ЯЗЫК.startsWith('be');

  function форма(n) {
    if (!РУССКИЙ) return n === 1 ? 0 : 1;
    const сотня = n % 100;
    if (сотня >= 11 && сотня <= 14) return 2;
    const единица = n % 10;
    if (единица === 1) return 0;
    if (единица >= 2 && единица <= 4) return 1;
    return 2;
  }

  // Пустая строка от getMessage означает «такого ключа нет». Показать пустоту
  // было бы худшим из возможных: интерфейс молча теряет смысл. Показываем сам
  // ключ — некрасиво, зато видно сразу.
  function t(ключ, ...подстановки) {
    const s =
      chrome.i18n && chrome.i18n.getMessage
        ? chrome.i18n.getMessage(ключ, подстановки.map(String))
        : '';
    return s || '[' + ключ + ']';
  }

  // Число со словом: n(3, 'plural_record') → «3 записи» / «3 records».
  function n(число, ключ) {
    const формы = t(ключ).split('|');
    const i = форма(число);
    return число + ' ' + (формы[i] !== undefined ? формы[i] : формы[формы.length - 1]);
  }

  // Метка поля из декларации. Декларация — данные, и её текст двуязычен прямо
  // в JSON: {"ru": "…", "en": "…"}. Строка вместо объекта означает, что автор
  // декларации дал один язык — показываем как есть, выдумывать перевод нельзя.
  function текст(значение) {
    if (значение == null) return '';
    if (typeof значение === 'string') return значение;
    if (typeof значение !== 'object') return String(значение);
    if (значение[ЯЗЫК]) return значение[ЯЗЫК];
    const короткий = ЯЗЫК.split('-')[0];
    if (значение[короткий]) return значение[короткий];
    if (значение.en) return значение.en;
    const первый = Object.keys(значение)[0];
    return первый ? значение[первый] : '';
  }

  self.РЕНТГЕН_I18N = { t, n, текст, язык: ЯЗЫК, русский: РУССКИЙ };
})();
